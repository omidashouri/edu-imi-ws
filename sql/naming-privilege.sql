INSERT INTO CRM.TBL_ROLE_PRIVILEGE_API (ID, ROLE_API_ID, PRIVILEGE_API_ID)
SELECT CRM.SEQ_ROLE_PRIVILEGE_API.NEXTVAL,
       r.ID,
       p.ID
  FROM CRM.TBL_ROLE_API r
  CROSS JOIN CRM.TBL_PRIVILEGE_API p
 WHERE r.NAME = 'ROLE_ADMIN'
   AND r.DELETE_DATE_TS IS NULL
   AND p.DELETE_DATE_TS IS NULL
   AND p.NAME LIKE 'API_%'
   AND NOT EXISTS (
         SELECT 1
           FROM CRM.TBL_ROLE_PRIVILEGE_API rp
          WHERE rp.ROLE_API_ID = r.ID
            AND rp.PRIVILEGE_API_ID = p.ID
   );

COMMIT;
